"""Host timezone detection + the firmware's supported-zone table.

The device carries no tzdata: components/timezone/timezone.c compiles in its own
IANA-name -> POSIX-TZ-rule table (generated by tools/gen_tz_table.py). Since
firmware 1.10.1 that table holds the whole IANA database, so validation here is
about catching a host zone the *device build* does not know — `cfg set timezone`
fails closed with ESP_ERR_INVALID_ARG on an unknown name, which used to surface
as an unfixable "Timezone: FAIL" at verification time (America/La_Paz, 2026-08).

Never flash a zone this module rejects: the on-boarding would fail verification,
and the device would fall back to a fixed offset for scheduling.
"""

from __future__ import annotations

import datetime

from .tz_zone_table import TZDATA_VERSION, ZONES

# Mirrors k_tz_zones in components/timezone/tz_zone_table.inc; both are
# generated by tools/gen_tz_table.py and a test asserts they match.
FIRMWARE_SUPPORTED_ZONES = ZONES
FIRMWARE_TZDATA_VERSION = TZDATA_VERSION


def local_iana_zone() -> str:
    """The PC's IANA timezone name.

    tzlocal is the only reliable cross-platform way to get an IANA name (on
    Windows the OS speaks registry names, not IANA). Falls back to UTC with the
    caller expected to surface the degradation.
    """
    try:
        import tzlocal
        name = str(tzlocal.get_localzone_name() or "").strip()
        if name:
            return name
    except Exception:
        pass
    # POSIX fallback: /etc/timezone or a TZ env var that looks IANA-ish.
    import os
    tz = os.environ.get("TZ", "")
    if "/" in tz:
        return tz
    try:
        text = open("/etc/timezone", encoding="utf-8").read().strip()
        if "/" in text:
            return text
    except OSError:
        pass
    return "UTC"


def firmware_supports(zone: str) -> bool:
    return zone in FIRMWARE_SUPPORTED_ZONES


def utc_offset_label(now: datetime.datetime | None = None) -> str:
    """e.g. 'UTC+02:00' for the local clock right now."""
    now = now or datetime.datetime.now().astimezone()
    off = now.utcoffset() or datetime.timedelta(0)
    total = int(off.total_seconds())
    sign = "+" if total >= 0 else "-"
    total = abs(total)
    return f"UTC{sign}{total // 3600:02d}:{(total % 3600) // 60:02d}"


def setup_zone(latitude: str, longitude: str, selected: str) -> tuple[str, float | None, float | None]:
    """Fallback zone for initial setup; the laptop clock is never an input.

    With coordinates we resolve the fallback unless a zone is explicitly entered.
    If the map has no match,
    or coordinates are unknown, the operator must explicitly choose a zone.
    Both coordinates travel with the provisioning plan instead of disappearing
    after choosing the timezone.
    """
    import math
    latitude, longitude, selected = latitude.strip(), longitude.strip(), selected.strip()
    lat = lon = None
    resolved = None
    if latitude or longitude:
        try:
            lat, lon = float(latitude), float(longitude)
            if (not math.isfinite(lat) or not math.isfinite(lon)
                    or not -90 <= lat <= 90 or not -180 <= lon <= 180):
                raise ValueError
        except ValueError:
            raise ValueError('Enter both deployment coordinates: latitude −90…90 and longitude −180…180.') from None
        if (lat, lon) != (0, 0):
            try:
                from .tz_geo import zone_for
                resolved = zone_for(lat, lon)
            except (RuntimeError, ImportError):
                if not selected:
                    raise ValueError('Coordinate timezone lookup unavailable; choose the fallback zone explicitly.') from None
    zone = selected or resolved
    if not zone:
        raise ValueError('Choose the fallback IANA timezone, or enter coordinates that resolve to one. The laptop timezone is not used.')
    if not firmware_supports(zone):
        raise ValueError(f"Deployment timezone '{zone}' is not in the firmware zone table.")
    return zone, lat, lon
